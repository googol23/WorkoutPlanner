"""Garmin operations consumed by the local CLI. No network or SDK imports."""

from typing import Any, Protocol


class ActivityReader(Protocol):
    def get_activities(self, *, start: int, limit: int, activitytype: str | None) -> list: ...
    def get_activities_by_date(self, start: str, end: str, /) -> list: ...
    def get_activity(self, activity_id: str, /) -> dict: ...
    def get_activity_details(self, activity_id: str, /, *, maxpoly: int) -> dict | None: ...
    def get_activity_splits(self, activity_id: str, /) -> Any: ...
    def get_activity_step_details(self, activity_id: str, /) -> Any: ...
    def get_activity_hr_in_timezones(self, activity_id: str, /) -> Any: ...
    def get_activity_power_in_timezones(self, activity_id: str, /) -> Any: ...
    def get_activity_weather(self, activity_id: str, /) -> Any: ...
    def get_activity_exercise_sets(self, activity_id: str, /) -> dict | None: ...


class WorkoutPublisher(Protocol):
    def get_workouts(self, *, start: int, limit: int, my_workouts_only: bool) -> list: ...
    def get_workout_by_id(self, workout_id: str, /) -> dict: ...
    def upload_running_workout(self, workout: Any, /) -> dict: ...
    def upload_cycling_workout(self, workout: Any, /) -> dict: ...
    def upload_strength_workout(self, workout: Any, /) -> dict: ...
    def get_scheduled_workouts(self, year: int, month: int, /) -> dict: ...
    def schedule_workout(self, workout_id: str | int, day: str, /) -> Any: ...
    def delete_workout(self, workout_id: str, /) -> Any: ...


def upload_for_sport(api: WorkoutPublisher, sport: str, workout: Any) -> dict:
    if sport == "running":
        return api.upload_running_workout(workout)
    if sport == "cycling":
        return api.upload_cycling_workout(workout)
    if sport == "strength_training":
        return api.upload_strength_workout(workout)
    raise ValueError(f"Unsupported Garmin workout sport: {sport}")
